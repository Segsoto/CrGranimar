import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const sources = ['tokens', 'base', 'components', 'home', 'works'];
const parts = await Promise.all(sources.map(name =>
  readFile(new URL(`styles/src/${name}.css`, root), 'utf8')
));
const banner = '/* Generated by scripts/build-styles.mjs. Edit styles/src/*.css. */\n';
const output = banner + parts.map((css, i) =>
  `\n/* Source: ${sources[i]}.css */\n${css.trim()}\n`
).join('');
const destination = new URL('styles/global.css', root);

if (process.argv.includes('--check')) {
  const current = await readFile(destination, 'utf8');
  if (current !== output) {
    console.error('Styles are out of date. Run: node scripts/build-styles.mjs');
    process.exitCode = 1;
  } else {
    console.log('Styles match their source files.');
  }
} else {
  await writeFile(destination, output);
  console.log(`Built styles/global.css from ${sources.length} source files.`);
}
